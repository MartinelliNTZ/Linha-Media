    OUTPUT = 'OUTPUT'
    INPUT = 'INPUT'
    INPUT_2 = 'INPUT_2'
    CONEXAO_OUTPUT = 'CONEXAO_OUTPUT'
    CRITERIO_PROXIMIDADE = 'CRITERIO_PROXIMIDADE'
