    def processAlgorithm(self, parameters, context, feedback):
        source = self.parameterAsSource(parameters, self.INPUT, context)
        source2 = self.parameterAsSource(parameters, self.INPUT_2, context)
        particoes = self.parameterAsInt(parameters, self.PARTICOES, context)
        criterio = self.parameterAsInt(parameters, self.CRITERIO_PROXIMIDADE, context)
        estilo = self.parameterAsInt(parameters, self.ESTILO_CONEXAO, context)
        estilo_mestra = self.parameterAsInt(parameters, self.ESTILO_LINHA_MESTRA, context)
        resolve_pontas = self.parameterAsBool(parameters, self.RESOLVER_ORFAOS_PONTAS, context)
        reducao = self.parameterAsDouble(parameters, self.REDUCAO_FILTRO, context)
        espacamento = self.parameterAsDouble(parameters, self.ESPACAMENTO, context)

        # 1. Extração e Validação (Delegado para VectorUtils)
        linha1, linha2, crs_final = VectorUtils.extract_two_features(source, source2, context)
        if linha1 is None:
            raise QgsProcessingException(self.tr('Erro de Seleção: Escolha 2 feições na mesma camada ou 1 em cada camada.'))

        # 2. Lógica de Pipeline Otimizada
        g1, g2 = VectorUtils.align_line_pair(linha1.geometry(), linha2.geometry())

        # Determinar o número alvo de segmentos (partições) baseado no maior valor
        v_count1 = sum(1 for _ in g1.vertices())
        v_count2 = sum(1 for _ in g2.vertices())
        target_n = max(particoes, v_count1 - 1, v_count2 - 1)
        
        # Determinar quais dados precisamos calcular para evitar duplicidade
        needs_near = (estilo_mestra == 1 or estilo == 0)
        needs_interp = (estilo_mestra == 0 or estilo == 2 or estilo == 1) # Perpendicular também precisa de interp
        needs_1to1 = (estilo_mestra == 2 or estilo == 3)
        
        near_conns = []
        fixed_conns = []
        interp_conns = []
        perp_results = []

        # A. Processamento por Proximidade
        if needs_near:
            feedback.pushInfo(self.tr('Calculando conexões por Proximidade...'))
            near_conns = ConnectionJudge.solve_nearest_with_criteria(g1, g2, criterio, target_n, resolve_pontas)
            near_conns = VectorUtils.filter_connections(near_conns, g1, g2, crs_final, reducao)

        # B. Processamento por Interpolação (Ponto a Ponto)
        if needs_interp:
            feedback.pushInfo(self.tr('Calculando conexões por Interpolação...'))
            m_results, c_results, p_results = VectorUtils.generate_linhamestra_elements(g1, g2, target_n, feedback)
            interp_conns = VectorUtils.filter_connections(c_results, g1, g2, crs_final, reducao)
            perp_results = p_results # As perpendiculares são geradas no fluxo de interpolação
            interp_mestra_results = m_results

        # C. Processamento 1:1
        if needs_1to1:
            feedback.pushInfo(self.tr('Calculando conexões por Espaçamento Fixo (1:1)...'))
            g_pai, g_mae = VectorUtils.align_by_endpoint_logic(linha1.geometry(), linha2.geometry())
            fixed_conns = VectorUtils.generate_1to1_connections(g_pai, g_mae, espacamento)
            fixed_conns = VectorUtils.filter_connections(fixed_conns, g_pai, g_mae, crs_final, reducao)

        # 3. Definição da Linha Mestra Final
        if estilo_mestra == 1:
            mestra_final = VectorUtils.generate_mestra_from_connections(near_conns)
        elif estilo_mestra == 2:
            mestra_final = VectorUtils.generate_mestra_from_connections(fixed_conns)
        else:
            mestra_final = VectorUtils.generate_mestra_from_connections(interp_conns)

        # 4. Seleção do estilo de conexão para saída
        if estilo == 0:
            conexao_final_results = near_conns
        elif estilo == 1: # Perpendicular
            conexao_final_results = perp_results
        elif estilo == 3: # 1:1
            conexao_final_results = fixed_conns
        else: # Conexão Direta (Ponto a Ponto)
            conexao_final_results = interp_conns

        # Definir os campos de saída (ID do segmento)
        fields_mestra = QgsFields()
        fields_mestra.append(QgsField('id_segmento', QVariant.Int))
        fields_mestra.append(QgsField('dist_mae', QVariant.Double))
        
        (sink, dest_id) = self.parameterAsSink(
            parameters, 
            self.OUTPUT,
            context, 
            fields_mestra, 
            QgsWkbTypes.LineString, 
            crs_final # CRS da primeira camada
        )

        # Configurar o sink para as conexões (Unificado)
        fields_conexao = QgsFields()
        fields_conexao.append(QgsField('id_conexao', QVariant.Int))
        fields_conexao.append(QgsField('id_pai', QVariant.Double))
        fields_conexao.append(QgsField('id_mae', QVariant.Double))
        fields_conexao.append(QgsField('id_origem', QVariant.Double))
        (sink_conexao, dest_id_conexao) = self.parameterAsSink(
            parameters,
            self.CONEXAO_OUTPUT,
            context,
            fields_conexao,
            QgsWkbTypes.LineString,
            crs_final
        )

        # 3. Escrita dos Resultados (Orquestração pura)
        feedback.pushInfo(self.tr('Escrevendo feições na camada de saída...'))

        def write_results(results, sink, fields):
            for res in results:
                if feedback.isCanceled(): break
                attrs = [
                    res.get('id', 0),
                    res.get('id_pai', 0),
                    res.get('id_mae', 0),
                    res.get('id_origem', 0)
                ]
                feat = VectorUtils.create_feature(res['geom'], fields, attrs)
                sink.addFeature(feat, QgsFeatureSink.FastInsert)

        # Mestra precisa de um campo extra (dist_mae), então fazemos manual
        for i, res in enumerate(mestra_final):
            if feedback.isCanceled(): break
            feat = VectorUtils.create_feature(res['geom'], fields_mestra, [res['id'], res['dist']])
            sink.addFeature(feat, QgsFeatureSink.FastInsert)

        write_results(conexao_final_results, sink_conexao, fields_conexao)

        return {
            self.OUTPUT: dest_id, 
            self.CONEXAO_OUTPUT: dest_id_conexao
        }

